export const thumbnailUrl = (p: Product) => `${import.meta.env.BASE_URL}thumbs/${p.id}.webp`;

export const formatPrice = (n: number) =>
  new Intl.NumberFormat('en-IN', { style: 'currency', currency: 'INR', maximumFractionDigits: 0 }).format(n);
